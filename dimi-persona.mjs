export function dimiChatModelFromEnv(env = process.env) {
  const model = env.GEMINI_CHAT_MODEL || 'gemini-3.5-flash-lite';
  return createGeminiModel({ apiKey: env.GEMINI_API_KEY, model,
    thinkingLevel: model === 'gemini-3.5-flash-lite' ? 'minimal' : undefined });
}
